import 'zone.js/node';
import '@angular/compiler';
import assert from 'node:assert/strict';
import { DOCUMENT } from '@angular/common';
import { TestBed } from '@angular/core/testing';
import { BrowserDynamicTestingModule, platformBrowserDynamicTesting } from '@angular/platform-browser-dynamic/testing';
import { SuperAdminStore } from '../src/app/features/super-admin/super-admin.store';
const storage = new Map<string, string>();
Object.defineProperty(globalThis, 'localStorage', { value: { getItem: (k: string) => storage.get(k) ?? null, setItem: (k: string, v: string) => storage.set(k, v) }, configurable: true });
TestBed.initTestEnvironment(BrowserDynamicTestingModule, platformBrowserDynamicTesting());
TestBed.configureTestingModule({ providers: [{ provide: DOCUMENT, useValue: { body: null, querySelectorAll: () => [] } }] });
const store = TestBed.inject(SuperAdminStore);
assert.equal(store.totalMRR(), store.schools().reduce((sum, s) => sum + store.monthlyRevenue(s.id), 0), 'School revenue must match subscription MRR');
assert.equal(store.subscriptions().find(s => s.plan === 'enterprise')!.amount, 6000000, 'Annual price is 12 monthly payments');
assert.ok(store.overdueBalance() > 0);
const invoice = store.overdueInvoices()[0];
const overdue = store.overdueBalance();
store.recordPayment(invoice.id);
assert.equal(store.overdueBalance(), overdue - invoice.amount);
const auditCount = store.auditLog().length;
store.recordPayment(invoice.id);
assert.equal(store.auditLog().length, auditCount, 'Cannot record a payment twice');
assert.ok(!store.attention().some(a => a.id === invoice.id), 'Paid invoice disappears from attention');
const schoolId = store.saveSchool({ name: 'Workflow Test School', location: 'Arusha', type: 'primary', plan: 'starter', contactName: 'Test Admin', contactEmail: 'test@example.test', contactPhone: '+255000000000' });
const sub = store.subscriptions().find(s => s.schoolId === schoolId)!;
assert.equal(sub.status, 'trial');
const oldEnd = +new Date(sub.trialEndsAt!);
store.extendTrial(sub.id);
assert.equal(+new Date(store.subscriptions().find(s => s.id === sub.id)!.trialEndsAt!), oldEnd + 7 * 86400000);
store.saveSubscription(sub.id, 'enterprise', 'annual');
store.activateSubscription(sub.id);
assert.equal(store.monthlyRevenue(schoolId), 500000);
assert.equal(store.schools().find(s => s.id === schoolId)!.plan, 'enterprise');
assert.equal(store.schools().find(s => s.id === schoolId)!.status, 'active');
const invoiceCount = store.invoices().length;
store.activateSubscription(sub.id);
assert.equal(store.invoices().length, invoiceCount, 'Repeated activation cannot create duplicate invoices');
store.setSchoolStatus(schoolId, 'suspended', '');
assert.equal(store.schools().find(s => s.id === schoolId)!.status, 'active', 'Suspension requires a reason');
store.setSchoolStatus(schoolId, 'suspended', 'Demo support review');
assert.equal(store.schools().find(s => s.id === schoolId)!.status, 'suspended');
store.inviteSchoolAdmin(schoolId);
assert.equal(store.schools().find(s => s.id === schoolId)!.adminInvited, true);
store.saveLead({ schoolName: 'Lead Conversion School', contactName: 'Test', contactEmail: 'lead@example.test', contactPhone: '', location: 'Mwanza', source: 'website', status: 'won', studentCount: 300, notes: '', owner: 'Test', followUp: '2020-01-01' });
const lead = store.leads()[0];
store.convertLead(lead.id);
const schoolsAfterConversion = store.schools().length;
store.convertLead(lead.id);
assert.equal(store.schools().length, schoolsAfterConversion, 'Lead converts only once');
assert.ok(store.leads().find(l => l.id === lead.id)!.convertedSchoolId);
assert.equal(store.saveAdmin({ name: 'Support', email: 'support@example.test', role: 'Support' }), '');
assert.ok(store.saveAdmin({ name: 'Duplicate', email: 'SUPPORT@example.test', role: 'Billing' }));
assert.ok(store.saveAdmin({ name: 'Changed' }, 'owner'));
store.saveSettings({ platformName: 'Demo Academy', trialDays: 14 });
TestBed.flushEffects();
const restored = TestBed.runInInjectionContext(() => new SuperAdminStore());
assert.equal(restored.settings().platformName, 'Demo Academy');
assert.equal(restored.schools().length, store.schools().length);
assert.ok(restored.subscriptions()[0].renewalDate instanceof Date, 'Stored dates are restored');
assert.equal(restored.totalMRR(), store.totalMRR());
assert.equal(restored.overdueBalance(), store.overdueBalance());
assert.ok(restored.recentActivity().every((entry, i, logs) => !i || +new Date(logs[i-1].timestamp) >= +new Date(entry.timestamp)));
TestBed.flushEffects(); TestBed.resetTestingModule();
console.log('Super admin checks passed: revenue, payments, school lifecycle, trial extension, lead conversion, access records, chronological activity and persistence.');
