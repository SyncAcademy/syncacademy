import 'zone.js/node';
import '@angular/compiler';
import assert from 'node:assert/strict';
import { DOCUMENT } from '@angular/common';
import { TestBed } from '@angular/core/testing';
import { BrowserDynamicTestingModule, platformBrowserDynamicTesting } from '@angular/platform-browser-dynamic/testing';
import { BursarStore } from '../src/app/features/bursar/bursar.store';

const storage = new Map<string, string>();
Object.defineProperty(globalThis, 'sessionStorage', { value: { getItem: (k: string) => storage.get(k) ?? null, setItem: (k: string, v: string) => storage.set(k, v) }, configurable: true });
TestBed.initTestEnvironment(BrowserDynamicTestingModule, platformBrowserDynamicTesting());
TestBed.configureTestingModule({ providers: [{ provide: DOCUMENT, useValue: { body: null, querySelectorAll: () => [] } }] });
const store = TestBed.inject(BursarStore);
assert.equal(store.accounts().length, 268);
assert.equal(store.summary().balance, 0, 'The finance ledger starts empty, without invented payments');
const input = { classId: 'c-1', term: 'Term 1', name: 'Tuition', amount: 100000, due: '2026-02-01' };
assert.ok(store.saveFee({ ...input, amount: 1.5 }));
assert.ok(store.saveFee({ ...input, amount: NaN }));
assert.ok(store.saveFee({ ...input, due: '2026-02-30' }));
assert.ok(store.saveFee({ ...input, due: '2025-02-01' }));
assert.equal(store.saveFee(input), null);
const fee = store.fees()[0];
assert.ok(store.saveFee(input), 'Duplicate class/term fee rejected');
assert.equal(store.saveFee({ ...input, amount: 120000 }, fee.id), null);
assert.equal(store.saveFee(input, fee.id), null);
const count = store.eligible(fee).length;
assert.equal(store.applyFee(fee.id), null);
assert.equal(store.summary().expected, count * input.amount);
assert.ok(store.applyFee(fee.id), 'Repeat application never duplicates charges');
assert.equal(store.charges().length, count);
assert.ok(store.saveFee({ ...input, amount: 200000 }, fee.id), 'Applied fees are immutable');
const studentId = store.charges()[0].studentId;
const payment = { studentId, term: 'Term 1', amount: 40000, method: 'Bank transfer', reference: 'TX-TEST-001', date: '2026-02-02' };
assert.ok(store.recordPayment({ ...payment, term: 'Term 2' }), 'Payments cannot be credited to an uncharged term');
assert.ok(store.recordPayment({ ...payment, amount: 100001 }), 'Overpayment rejected');
assert.ok(store.recordPayment({ ...payment, reference: '' }));
assert.ok(store.recordPayment({ ...payment, date: '2099-01-01' }));
assert.equal(store.recordPayment(payment), null);
assert.ok(store.recordPayment(payment), 'Duplicate external reference rejected');
assert.equal(store.totals(studentId).balance, 60000);
assert.equal(store.totals(studentId).overdue, 60000, 'Partial payment reduces overdue fees');
const receipt = structuredClone(store.payments()[0]);
assert.equal(store.adjust({ studentId, term: 'Term 1', kind: 'Scholarship', amount: 10000, reason: 'Approved school scholarship.' }), null);
assert.equal(store.totals(studentId).balance, 50000);
assert.ok(store.adjust({ studentId, term: 'Term 1', kind: 'Discount', amount: 50001, reason: 'Credit cannot exceed balance.' }));
assert.ok(store.adjust({ studentId, term: 'Term 1', kind: 'Unknown', amount: 1, reason: 'Invalid adjustment type.' }));
assert.equal(store.adjust({ studentId, term: 'Term 1', kind: 'Debit correction', amount: 5000, reason: 'Corrected a prior credit entry.' }), null);
assert.equal(store.totals(studentId).balance, 55000);
assert.deepEqual(store.payments()[0], receipt, 'Adjustments never rewrite receipts');
assert.ok(store.voidPayment(receipt.id, 'short'));
assert.equal(store.voidPayment(receipt.id, 'Bank transaction was entered against the wrong student.'), null);
assert.equal(store.totals(studentId).balance, 95000);
assert.equal(store.payments()[0].amount, 40000);
assert.ok(store.payments()[0].voidAt);
assert.ok(store.voidPayment(receipt.id, 'Cannot void the same receipt twice.'));
assert.equal(store.recordPayment({ ...payment, amount: 95000, reference: 'TX-TEST-002' }), null);
assert.notEqual(store.payments()[1].receipt, receipt.receipt, 'Receipt numbers are never reused');
assert.equal(store.totals(studentId).balance, 0);
assert.equal(store.registry.saveStudent({ name: 'New Finance Student', number: 'FIN-NEW-001', gender: 'F', birthDate: '2012-01-01', address: '' }, undefined, 'c-1'), null);
assert.equal(store.eligible(fee).length, 1);
assert.equal(store.applyFee(fee.id), null);
assert.equal(store.charges().length, count + 1, 'Late enrolment receives exactly one charge');
const before = JSON.stringify(store.charges());
store.years.select('register', 'ay-2');
assert.equal(store.accounts().length, 269, 'Registrar browsing selection cannot alter bursar accounts');
store.years.select('bursar', 'ay-2');
assert.equal(store.accounts().length, 0);
assert.equal(store.payments().length, 0);
assert.equal(store.readOnly(), true);
assert.ok(store.saveFee(input));
assert.ok(store.applyFee(fee.id));
assert.ok(store.recordPayment(payment));
assert.ok(store.voidPayment(receipt.id, 'Attempting historical correction.'));
assert.ok(store.adjust({ studentId, term: 'Term 1', kind: 'Discount', amount: 1, reason: 'Historical changes forbidden.' }));
store.years.select('bursar', 'ay-1');
assert.equal(JSON.stringify(store.charges()), before);
assert.equal(store.years.teacherYear()?.id, 'ay-1');
TestBed.flushEffects();
const restored = TestBed.runInInjectionContext(() => new BursarStore());
assert.deepEqual(restored.summary(), store.summary());
assert.deepEqual(restored.payments(), store.payments());
TestBed.flushEffects(); TestBed.resetTestingModule();
console.log('Bursar checks passed: fee validation, immutable/idempotent billing, late enrolment, payment references, overpayment prevention, receipts, adjustments, voids, year isolation, closed-year guards and persistence.');
