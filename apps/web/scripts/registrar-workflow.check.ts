import 'zone.js/node';
import '@angular/compiler';
import assert from 'node:assert/strict';
import { DOCUMENT } from '@angular/common';
import { TestBed } from '@angular/core/testing';
import { BrowserDynamicTestingModule, platformBrowserDynamicTesting } from '@angular/platform-browser-dynamic/testing';
import { RegistrarStore } from '../src/app/features/registrar/registrar.store';
import { AcademicSetupStore } from '../src/app/features/academic/academic-setup.store';
import { AcademicStore } from '../src/app/features/academic/academic.store';

const storage = new Map<string, string>();
Object.defineProperty(globalThis, 'sessionStorage', { value: {
  getItem: (key: string) => storage.get(key) ?? null,
  setItem: (key: string, value: string) => storage.set(key, value),
}, configurable: true });
TestBed.initTestEnvironment(BrowserDynamicTestingModule, platformBrowserDynamicTesting());
TestBed.configureTestingModule({ providers: [{ provide: DOCUMENT, useValue: { body: null, querySelectorAll: () => [] } }] });
const registry = TestBed.inject(RegistrarStore);
const teacher = registry.teacher;
const years = registry.years;
assert.equal(registry.year()?.id, 'ay-1');
assert.equal(registry.stats().active, 268);
assert.equal(registry.counts().find(c => c.id === 'c-3')?.active, 42);
assert.equal(registry.decideAdmission('application-demo-2', 'accepted', 'c-3', ''), null);
assert.equal(registry.stats().active, 269);
assert.equal(registry.head.classes().find(c => c.id === 'c-3')?.studentCount, 43);
assert.ok(registry.decideAdmission('application-demo-2', 'accepted', 'c-3', ''), 'Already-decided applications cannot be admitted twice');
const admittedId = registry.admissions().find(a => a.id === 'application-demo-2')!.studentId!;
assert.equal(registry.contacts(admittedId).length, 1);
assert.equal(registry.contacts(admittedId)[0].verifiedAt, null);
assert.ok(registry.enrol(admittedId, 'c-4'), 'Duplicate academic-year enrolments are blocked');
assert.ok(registry.decideAdmission('application-demo-1', 'rejected', '', 'short'));
assert.equal(registry.decideAdmission('application-demo-1', 'rejected', '', 'Documents not provided for this admission cycle.'), null);
assert.ok(registry.saveStudent({ number: '', name: 'Invalid Date', gender: 'F', birthDate: '2012-02-30', address: '' }));
assert.equal(registry.saveStudent({ number: 'SA-TEST-001', name: 'Test Student', gender: 'F', birthDate: '2012-04-15', address: 'Dar es Salaam' }, undefined, 'c-1'), null);
assert.ok(registry.saveStudent({ number: 'SA-TEST-001', name: 'Duplicate Number', gender: 'M', birthDate: '2012-04-15', address: '' }));
const extra = registry.allStudents().find(s => s.number === 'SA-TEST-001')!;
assert.equal(registry.enrolment(extra.id)?.classId, 'c-1');
const lockedMarks = JSON.stringify(teacher.state().marks['ta-1']);
assert.ok(registry.publishRoster('c-1').locked >= 1);
assert.equal(JSON.stringify(teacher.state().marks['ta-1']), lockedMarks, 'Approved assessment rosters cannot be rewritten');
const oldGrade = teacher.state().marks['ta-3'][0].marksValue;
assert.equal(registry.publishRoster('c-3').updated, 1);
assert.equal(teacher.state().marks['ta-3'].length, 43);
assert.equal(teacher.state().marks['ta-3'][0].marksValue, oldGrade);
assert.equal(teacher.state().marks['ta-3'].find(m => m.studentNumber === registry.student(admittedId)!.number)?.marksValue, null);
assert.equal(teacher.assignments().find(a => a.id === 'ta-3')?.rosterStatus, 'pending');
const departure = registry.enrolments().find(e => e.classId === 'c-3' && e.studentId !== admittedId)!;
const departureNumber = registry.student(departure.studentId)!.number;
assert.equal(registry.move(departure.studentId, 'transferred_out', '', 'Family relocated to another school district.'), null);
assert.equal(registry.history(departure.studentId)[0].status, 'transferred_out');
assert.equal(registry.publishRoster('c-3').updated, 1);
assert.ok(!teacher.state().marks['ta-3'].some(m => m.studentNumber === departureNumber));
assert.ok(registry.archivedResults(departure.studentId).some(m => m.studentNumber === departureNumber), 'Removed draft entries are archived, not discarded');

const academic = TestBed.inject(AcademicStore);
assert.equal(academic.prepareReports('Form 1A'), null);
const guardian = registry.guardians()[0];
assert.ok(registry.verifyGuardian(guardian.id, 'short'));
assert.equal(registry.verifyGuardian(guardian.id, 'Confirmed phone details with the parent in person.'), null);
const report = registry.reports.forYear('ay-1').find(r => r.studentNumber === registry.student(guardian.studentIds[0])!.number)!;
assert.ok(report.recipients.some(g => g.verified));
assert.equal(registry.saveGuardian({ ...guardian, phone: '+255700000999', studentId: guardian.studentIds[0] }, guardian.id), null);
assert.equal(registry.guardians().find(g => g.id === guardian.id)?.verifiedAt, null, 'Changing contact details revokes verification');
assert.ok(registry.reports.forYear('ay-1').find(r => r.id === report.id)!.recipients.every(g => !g.verified));
assert.equal(registry.linkGuardian(guardian.id, extra.id), null);
assert.ok(registry.linkGuardian(guardian.id, extra.id), 'Duplicate guardian links are rejected');

const setup = TestBed.inject(AcademicSetupStore);
assert.equal(setup.prepareClasses('ay-4'), null);
const target = registry.classesFor('ay-4').find(c => c.stream === 'Form 2A')!;
assert.equal(target.enrolmentStatus, 'draft');
assert.ok(registry.promote([admittedId], 'ay-4', target.id), 'Draft classes reject progression');
registry.head.classes.update(list => list.map(c => c.id === target.id ? { ...c, enrolmentStatus: 'open' } : c));
const sourceBefore = JSON.stringify(registry.history(admittedId));
assert.equal(registry.promote([admittedId], 'ay-4', target.id), null);
assert.equal(JSON.stringify(registry.history(admittedId).filter(e => e.yearId === 'ay-1')), sourceBefore, 'Source-year records are unchanged by progression');
const targetCount = registry.head.classes().find(c => c.id === target.id)!.studentCount;
assert.ok(registry.promote([admittedId, extra.id], 'ay-4', target.id));
assert.equal(registry.head.classes().find(c => c.id === target.id)!.studentCount, targetCount, 'Progression rejects the whole batch if any target enrolment exists');
assert.ok(registry.promote([extra.id], 'ay-2', 'c-1'), 'Closed or earlier targets are rejected');

const classInput = { name: 'Test Class', stream: '', capacity: 1, status: 'draft', subjectIds: [setup.head.subjects()[0].id] };
assert.equal(setup.saveClass(classInput), null);
const created = setup.classes().find(c => c.name === 'Test Class')!;
const pupil = { number: 'CLASS-001', name: 'Class Test Pupil', gender: 'F', birthDate: '2012-04-15', address: '' };
assert.ok(registry.saveStudent(pupil), 'A class is mandatory');
assert.ok(registry.saveStudent(pupil, undefined, created.id), 'Draft classes reject registration');
assert.equal(setup.saveClass({ ...classInput, status: 'open' }, created.id), null);
assert.equal(registry.saveStudent(pupil, undefined, created.id), null);
assert.ok(registry.saveStudent({ ...pupil, number: 'CLASS-002' }, undefined, created.id), 'Full classes reject registration');
assert.ok(!registry.allStudents().some(s => s.number === 'CLASS-002'), 'Rejected registration leaves no orphan profile');
assert.ok(setup.deleteClass(created.id), 'Used classes cannot be deleted');
assert.equal(setup.saveClass({ ...classInput, status: 'closed' }, created.id), null);
const pupilId = registry.allStudents().find(s => s.number === pupil.number)!.id;
assert.ok(registry.move(pupilId, 'withdrawn', '', 'Testing a closed class update.'), 'Closed class edits are rejected');
assert.equal(setup.createTeacher('Test Teacher', 'teacher@example.test', '+255700123456', ''), null);
assert.ok(setup.pending().some(t => t.email === 'teacher@example.test'));
assert.ok(!setup.teachers().some(t => t.email === 'teacher@example.test'), 'Teacher awaits headmaster approval');
assert.ok(setup.createTeacher('Test Teacher', 'teacher@example.test', '+255700123456', ''), 'Duplicate teachers rejected');
const beforeGrade = teacher.grade('ta-1', 70);
assert.ok(setup.grading.save([{ label: 'A', minimum: 50 }, { label: 'B', minimum: 60 }], 50));
assert.equal(setup.grading.save([{ label: 'Pass', minimum: 50 }, { label: 'Fail', minimum: 0 }], 50), null);
assert.equal(teacher.grade('ta-1', 70), beforeGrade, 'Approved results retain original grading');
assert.equal(teacher.grade('ta-3', 70), 'Pass', 'Editable results use the new grading scheme');
const draft = teacher.assignments().find(a => a.id === 'ta-3')!;
teacher.confirmRoster(draft.id);
teacher.save(draft.id, teacher.entries(draft.id).map(m => ({ ...m, marksValue: 70 })));
assert.equal(teacher.submit(draft.id), true);
assert.equal(setup.grading.save([{ label: 'Excellent', minimum: 60 }, { label: 'Low', minimum: 0 }], 60), null);
assert.equal(teacher.grade(draft.id, 70), 'Pass', 'Submitted results freeze their grading scheme');

years.years.update(list => list.map(y => y.id === 'ay-1' ? { ...y, status: 'closed' } : y));
assert.equal(registry.readOnly(), true);
assert.ok(registry.enrol(extra.id, 'c-3'));
assert.ok(registry.publishRoster('c-3').error);
assert.ok(registry.verifyGuardian(guardian.id, 'Attempted closed-year update.'));
assert.equal(registry.promote([extra.id], 'ay-4', target.id), null, 'A closed source year can be read to create records in an open target year');
years.select('register', 'ay-4');
assert.equal(registry.stats().active, 2);
assert.equal(years.teacherYear()?.id, 'ay-1');
assert.equal(years.headYear()?.id, 'ay-1');
TestBed.flushEffects();
assert.ok(storage.get('syncacademy.registrar.v1'));
const restored = TestBed.runInInjectionContext(() => new RegistrarStore());
assert.equal(restored.stats().active, 2);
assert.equal(restored.history(admittedId).length, 2);
TestBed.flushEffects();
TestBed.resetTestingModule();
console.log('Registrar workflow checks passed: admissions, uniqueness, enrolment, class counts, safe roster publication, contact verification, report recipients, atomic progression, year isolation and persistence.');
