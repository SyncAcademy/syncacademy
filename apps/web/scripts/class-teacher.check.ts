import 'zone.js/node';
import '@angular/compiler';
import assert from 'node:assert/strict';
import { DOCUMENT } from '@angular/common';
import { TestBed } from '@angular/core/testing';
import { BrowserDynamicTestingModule, platformBrowserDynamicTesting } from '@angular/platform-browser-dynamic/testing';
import { TeacherClassStore } from '../src/app/features/teacher/teacher-class.store';
import { AcademicSetupStore } from '../src/app/features/academic/academic-setup.store';
import { HeadOversightStore } from '../src/app/features/headmaster/head-oversight.store';
import { AttendanceEntry } from '../src/app/core/services/attendance.service';

const storage = new Map<string, string>();
Object.defineProperty(globalThis, 'sessionStorage', { value: { getItem: (k: string) => storage.get(k) ?? null, setItem: (k: string, v: string) => storage.set(k, v) }, configurable: true });
TestBed.initTestEnvironment(BrowserDynamicTestingModule, platformBrowserDynamicTesting());
TestBed.configureTestingModule({ providers: [{ provide: DOCUMENT, useValue: { body: null, querySelectorAll: () => [] } }] });
const store = TestBed.inject(TeacherClassStore);
const setup = TestBed.inject(AcademicSetupStore);
const head = TestBed.inject(HeadOversightStore);
const roles = store.roles; const attendance = store.attendance; const teacher = store.teacher;
assert.equal(store.classes().length, 0, 'Subject teachers do not implicitly have class-teacher privileges');
assert.equal(store.results(true).length, 0);
assert.ok(store.results(false).every(r => !r.assignmentId.startsWith('academic-')), 'Subject performance is restricted to owned assignments');
assert.ok(roles.assign('c-1', 'u-6'), 'Inactive teachers cannot be assigned');
assert.equal(roles.assign('c-1', teacher.teacherId), null);
assert.equal(store.classes().length, 1);
assert.ok(store.results(true).some(r => r.subject === 'English Language'), 'Class teachers see results from other subjects in their class');
assert.ok(store.results(true).every(r => r.className === 'Form 1A'), 'Other classes remain out of scope');
const foreignId = 'academic-english-1a'; const beforeMarks = JSON.stringify(teacher.state().marks[foreignId]);
teacher.save(foreignId, []);
assert.equal(JSON.stringify(teacher.state().marks[foreignId]), beforeMarks, 'Class-teacher access does not grant marks editing');
assert.equal(teacher.submit(foreignId), false);
const date = '2026-09-23';
const roster = attendance.roster('c-1', date);
assert.equal(roster.length, 45);
const entries: AttendanceEntry[] = roster.map((r, i) => ({ ...r, status: i === 0 ? 'Absent' : 'Present', note: i === 0 ? 'Parent reported illness.' : '' }));
assert.ok(attendance.save('c-2', date, entries), 'Cannot record attendance for an unassigned class');
assert.ok(attendance.save('c-1', '2099-01-01', entries));
assert.ok(attendance.save('c-1', '2026-02-30', entries));
assert.ok(attendance.save('c-1', date, entries.slice(1)), 'Partial rosters cannot be saved');
assert.ok(attendance.save('c-1', date, entries.map((r, i) => i === 1 ? entries[0] : r)), 'Duplicate entries rejected');
assert.equal(attendance.save('c-1', date, entries), null);
assert.equal(store.sheets().length, 1);
assert.equal(head.attendanceSheets().length, 1, 'Headmaster can monitor class attendance');
assert.ok(head.activity().some(a => a.message.includes('attendance for ' + date)));
assert.ok(attendance.save('c-1', date, entries, 'short'));
assert.equal(attendance.save('c-1', date, entries.map(r => ({ ...r, status: 'Present' })), 'Parent confirmed that the student arrived later.'), null);
assert.equal(attendance.forYear('ay-1').length, 1, 'Daily summary counts latest version only');
assert.equal(attendance.revisions('ay-1').length, 2);
assert.equal(attendance.revisions('ay-1')[0].entries[0].status, 'Absent', 'Original attendance is preserved');
assert.equal(store.registry.move(entries[0].studentId, 'withdrawn', '', 'Student moved to another school.'), null);
assert.equal(attendance.roster('c-1', date).length, 45, 'Saved register retains its historical roster');
assert.equal(roles.assign('c-1', 'u-5'), null);
assert.equal(store.classes().length, 0, 'Replacing a class teacher revokes their access immediately');
assert.equal(store.results(true).length, 0);
assert.equal(store.sheets().length, 0);
assert.ok(attendance.save('c-1', date, entries, 'A former teacher cannot correct this record.'));
assert.equal(roles.assign('c-1', teacher.teacherId), null);
assert.equal(store.sheets().length, 1, 'Reassignment preserves saved records');
setup.head.staff.update(list => list.map(t => t.id === teacher.teacherId ? { ...t, status: 'inactive' } : t));
assert.equal(store.classes().length, 0);
assert.equal(teacher.assignments().length, 0);
setup.head.staff.update(list => list.map(t => t.id === teacher.teacherId ? { ...t, status: 'active' } : t));
assert.equal(setup.saveClass({ name: 'Test Teaching Class', stream: '', capacity: 10, status: 'open', subjectIds: ['s-1'] }), null);
const c = setup.classes().find(c => c.name === 'Test Teaching Class')!;
assert.equal(store.registry.saveStudent({ number: 'CT-TEST-001', name: 'Teaching Test Student', gender: 'F', birthDate: '2012-01-01', address: '' }, undefined, c.id), null);
assert.equal(store.academic.saveTeachingAssignment(teacher.teacherId, c.id, 's-1'), null);
const assignment = teacher.assignments().find(a => a.classId === c.id)!;
assert.ok(assignment, 'Academic subject allocation creates teacher assessment work');
assert.equal(teacher.entries(assignment.id).length, 1);
assert.equal(teacher.entries(assignment.id)[0].studentNumber, 'CT-TEST-001');
assert.equal(assignment.assessmentProgress.status, 'draft');
assert.ok(store.academic.saveTeachingAssignment('u-5', c.id, 's-1'), 'Duplicate active subject allocations are blocked');
assert.equal(store.classes().length, 1, 'A subject assignment does not create a class-teacher role');
setup.years.select('academic', 'ay-4');
assert.ok(roles.assign('c-1', teacher.teacherId), 'Class teacher cannot be assigned to another year’s class');
setup.years.select('academic', 'ay-1');
setup.years.select('teacher', 'ay-2');
assert.equal(store.classes().length, 0);
assert.equal(store.results(true).length, 0);
assert.equal(setup.years.academicYear()?.id, 'ay-1');
setup.years.select('teacher', 'ay-1');
setup.years.years.update(list => list.map(y => y.id === 'ay-1' ? { ...y, status: 'closed' } : y));
assert.equal(store.classes().length, 1, 'Historical class-teacher views remain available');
assert.ok(attendance.save('c-1', date, entries, 'Closed-year change is not permitted.'));
assert.ok(roles.assign('c-1', 'u-5'));
TestBed.flushEffects();
assert.ok(storage.get('syncacademy.class-teachers.v1'));
assert.ok(storage.get('syncacademy.attendance.v1'));
TestBed.resetTestingModule();
console.log('Class teacher checks passed: role assignment/revocation, subject allocation, scoped cross-subject viewing, marks ownership, attendance validation/corrections, historical rosters, oversight, year isolation and persistence.');
