import 'zone.js/node';
import '@angular/compiler';
import assert from 'node:assert/strict';
import { DOCUMENT } from '@angular/common';
import { TestBed } from '@angular/core/testing';
import { BrowserDynamicTestingModule, platformBrowserDynamicTesting } from '@angular/platform-browser-dynamic/testing';
import { AcademicStore, summarizeResults } from '../src/app/features/academic/academic.store';

const storage = new Map<string, string>();
Object.defineProperty(globalThis, 'sessionStorage', { value: {
  getItem: (key: string) => storage.get(key) ?? null,
  setItem: (key: string, value: string) => storage.set(key, value),
}, configurable: true });
TestBed.initTestEnvironment(BrowserDynamicTestingModule, platformBrowserDynamicTesting());
TestBed.configureTestingModule({ providers: [{ provide: DOCUMENT, useValue: { body: null, querySelectorAll: () => [] } }] });
const academic = TestBed.inject(AcademicStore);
const teacher = academic.teacher;
const years = academic.years;
assert.equal(academic.year()?.id, 'ay-1');
assert.equal(teacher.assignments().length, 5, 'School-wide fixtures cannot leak into another teacher account');
assert.equal(academic.assignments().length, 8);
assert.equal(summarizeResults(academic.approvedResults(), 'subject').length, 3);
assert.equal(summarizeResults(academic.approvedResults(), 'className').length, 2);
assert.ok(academic.results().every(r => Number.isFinite(r.mark) && r.mark >= 0 && r.mark <= 100));
const fixtureRows = academic.results().slice(0, 3).map((r, i) => ({ ...r, className: 'Example', passed: undefined, mark: [0, 35, 100][i] }));
assert.equal(summarizeResults(fixtureRows, 'className')[0].average, 45);
assert.equal(summarizeResults(fixtureRows, 'className')[0].passRate, 2 / 3 * 100);
assert.ok(academic.review('ta-3', 'approved'), 'Draft submissions cannot be approved');
assert.ok(academic.review('ta-2', 'returned', 'short'));
assert.equal(academic.review('ta-2', 'returned', 'Please verify the totals against your assessment sheet.'), null);
assert.equal(teacher.assignments().find(a => a.id === 'ta-2')?.assessmentProgress.status, 'returned');
assert.ok(teacher.notifications().some(n => n.relatedAssignmentId === 'ta-2' && n.type === 'marks_returned'));
assert.equal(teacher.submit('ta-2'), true);
assert.equal(academic.review('ta-2', 'approved'), null);
assert.equal(teacher.assignments().find(a => a.id === 'ta-2')?.assessmentProgress.status, 'approved');
assert.ok(academic.review('ta-2', 'returned', 'This is already approved.'), 'Reviewed records cannot be returned after approval');
assert.ok(academic.prepareReports('Form 2A'), 'Unapproved subjects block preparation');
years.select('head', 'ay-2');
assert.equal(academic.prepareReports('Form 1A'), null);
assert.equal(academic.reports().length, 45);
assert.ok(academic.reports().every(r => r.results?.length === 3 && r.academicApproved && r.status === 'generated'));
assert.equal(academic.reportStore.reports().length, 0, 'Headmaster selection remains independent');
years.select('head', 'ay-1');
assert.ok(academic.reportStore.reports().some(r => r.id.startsWith('academic-')));
assert.equal(academic.prepareReports('Form 1A'), null);
assert.equal(academic.reports().length, 45, 'Repeated preparation must not duplicate reports');
assert.ok(academic.reports().every(r => !academic.reportStore.eligible(r)), 'No delivery without verified guardians and head approval');

const slot = { className: 'Form 1A', subject: 'Mathematics', teacher: 'Invigilator One', room: 'Room A', date: '2026-10-01', start: '09:00', end: '11:00' };
assert.equal(academic.saveSlot(slot), null);
assert.ok(academic.saveSlot({ ...slot, className: 'Form 1B', start: '10:30', end: '12:00' }), 'Invigilator/room conflict must be blocked');
assert.equal(academic.saveSlot({ ...slot, start: '11:00', end: '12:00' }), null, 'Adjacent slots are valid');
assert.ok(academic.saveSlot({ ...slot, date: '2026-02-30' }));
assert.ok(academic.saveSlot({ ...slot, start: '25:00', end: '26:00' }));
assert.ok(academic.saveSlot({ ...slot, date: '2025-10-01' }));
assert.ok(academic.saveTeachingAssignment('u-4', 'c-1', 's-1'), 'Duplicate teaching assignments are rejected');
assert.equal(academic.saveTopic('ta-1', 'Revision exercises', '2026-10-03'), null);
const topic = academic.syllabus().at(-1)!;
academic.toggleTopic(topic.id);
assert.equal(academic.syllabus().find(t => t.id === topic.id)?.completed, true);
teacher.reportIssue('ta-3', { studentId: null, issueType: 'missing_student', description: 'A student was omitted from this class list.' });
const issue = academic.issues().at(-1)!;
assert.equal(academic.resolveIssue(issue.index, 'Checked the enrolment record and corrected the student list.'), null);
assert.ok(academic.issues().find(i => i.index === issue.index)?.resolvedAt);
assert.ok(teacher.notifications().some(n => n.type === 'roster_issue_resolved'));

assert.equal(academic.saveAssessment({ name: 'November revision', term: 'Term 3', deadline: '2026-11-10' }), null);
const exam = academic.assessments().find(a => a.name === 'November revision')!;
assert.ok(academic.assignAssessment(exam.id), 'Draft assessments cannot receive submissions');
assert.equal(academic.changeAssessment(exam.id, 'open'), null);
const previousMarks = JSON.stringify(teacher.state().marks['ta-2']);
assert.equal(academic.assignAssessment(exam.id), null);
academic.selectAssessment(exam.id);
assert.equal(academic.assignments().length, 8);
assert.equal(academic.results().length, 0, 'A new assessment must not reuse old marks');
assert.equal(JSON.stringify(teacher.state().marks['ta-2']), previousMarks);
assert.ok(academic.changeAssessment(exam.id, 'closed'), 'Unreviewed submissions prevent closure');
assert.ok(academic.assignAssessment(exam.id), 'No duplicate allocation');
const count = academic.yearAssignments().length;
years.select('academic', 'ay-2');
assert.equal(academic.assignments().length, 0);
assert.equal(academic.results().length, 0);
assert.equal(academic.reports().length, 0);
assert.equal(academic.readOnly(), true);
assert.equal(years.teacherYear()?.id, 'ay-1');
assert.ok(academic.saveAssessment({ name: 'Historical edit', term: 'Term 1', deadline: '2025-05-01' }));
assert.ok(academic.review('ta-2', 'approved'));
years.select('academic', 'ay-1');
assert.equal(academic.yearAssignments().length, count);
TestBed.flushEffects();
assert.ok(storage.get('syncacademy.academic.v1'));
const restored = TestBed.runInInjectionContext(() => new AcademicStore());
assert.equal(restored.assessments().length, 2);
assert.equal(restored.yearAssignments().length, count, 'Fixture migration must be idempotent');
TestBed.flushEffects();
TestBed.resetTestingModule();
console.log('Academic workflow checks passed: ownership, analytics, reviews, feedback, report handoff, scheduling conflicts, syllabus, issue resolution, assessment isolation, year guards and persistence.');
