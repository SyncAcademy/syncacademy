import 'zone.js/node';
import '@angular/compiler';
import assert from 'node:assert/strict';
import { DOCUMENT } from '@angular/common';
import { TestBed } from '@angular/core/testing';
import { BrowserDynamicTestingModule, platformBrowserDynamicTesting } from '@angular/platform-browser-dynamic/testing';
import { HeadOversightStore } from '../src/app/features/headmaster/head-oversight.store';
import { BursarStore } from '../src/app/features/bursar/bursar.store';
import { AcademicStore } from '../src/app/features/academic/academic.store';

const storage = new Map<string, string>();
Object.defineProperty(globalThis, 'sessionStorage', { value: { getItem: (k: string) => storage.get(k) ?? null, setItem: (k: string, v: string) => storage.set(k, v) }, configurable: true });
TestBed.initTestEnvironment(BrowserDynamicTestingModule, platformBrowserDynamicTesting());
TestBed.configureTestingModule({ providers: [{ provide: DOCUMENT, useValue: { body: null, querySelectorAll: () => [] } }] });
const head = TestBed.inject(HeadOversightStore);
const bursar = TestBed.inject(BursarStore);
const academic = TestBed.inject(AcademicStore);
const years = bursar.years;
assert.equal(head.enrolments().filter(e => e.status === 'active').length, 268);
assert.equal(head.financeSummary().paid, 0);
assert.deepEqual(head.results().filter(r => r.status === 'approved').map(r => r.grade), academic.approvedResults().map(r => r.grade));
assert.equal(bursar.saveFee({ classId: 'c-1', name: 'Tuition', amount: 100000, term: 'Term 1', due: '2026-02-01' }), null);
assert.equal(bursar.applyFee(bursar.fees()[0].id), null);
const studentId = bursar.charges()[0].studentId;
assert.equal(head.financeSummary().expected, bursar.summary().expected, 'Fee charges appear immediately in head reports');
assert.equal(bursar.recordPayment({ studentId, term: 'Term 1', amount: 20000, method: 'Cash', reference: '', date: '2026-02-02' }), null);
const receipt = bursar.payments()[0];
assert.equal(head.financeSummary().paid, 20000);
assert.ok(head.activity().some(a => a.owner === 'Bursar' && a.message.includes(receipt.receipt)));
assert.equal(bursar.adjust({ studentId, term: 'Term 1', amount: 5000, kind: 'Scholarship', reason: 'School scholarship awarded.' }), null);
assert.equal(head.accounts().find(a => a.id === studentId)?.balance, 75000);
assert.equal(bursar.voidPayment(receipt.id, 'Receipt entered against an incorrect payer.'), null);
assert.equal(head.financeSummary().paid, 0);
assert.ok(head.finance().payments[0].voidAt, 'Head can inspect the voided receipt history');
assert.ok(head.activity().some(a => a.message.includes('voided:')));
assert.equal(academic.review('ta-2', 'returned', 'Review the marks against the original script.'), null);
assert.ok(head.assignments().some(a => a.id === 'ta-2' && a.assessmentProgress.status === 'returned'));
assert.ok(head.activity().some(a => a.owner === 'Academic Master' && a.message.includes('returned')));
const enrollmentStudent = bursar.registry.enrolments().find(e => e.classId === 'c-3')!;
assert.equal(bursar.registry.move(enrollmentStudent.studentId, 'withdrawn', '', 'Family requested withdrawal from the school.'), null);
assert.equal(head.enrolments().filter(e => e.status === 'active').length, 267);
assert.ok(head.activity().some(a => a.owner === 'Registrar' && a.message.toLowerCase().includes('withdraw')));
const financeBefore = structuredClone(head.financeSummary());
const resultsBefore = structuredClone(head.results());
const activitiesBefore = head.activity().length;
years.select('bursar', 'ay-4'); years.select('academic', 'ay-2'); years.select('register', 'ay-3'); years.select('teacher', 'ay-2');
assert.deepEqual(head.financeSummary(), financeBefore, 'Staff year selections do not change the head finance view');
assert.deepEqual(head.results(), resultsBefore, 'Staff year selections do not change head results');
assert.equal(head.activity().length, activitiesBefore);
assert.equal(head.accountsFor('Term 2').reduce((s, a) => s + a.expected, 0), 0);
years.select('head', 'ay-2');
assert.equal(head.financeSummary().expected, 0);
assert.equal(head.finance().payments.length, 0);
assert.equal(head.results().length, 0);
assert.equal(head.activity().length, 0);
assert.equal(years.bursarYear()?.id, 'ay-4');
assert.equal(years.academicYear()?.id, 'ay-2');
assert.equal(years.registerYear()?.id, 'ay-3');
years.select('head', 'ay-1');
assert.deepEqual(head.financeSummary(), financeBefore);
const stateBefore = JSON.stringify(bursar.forYear('ay-1'));
head.finance(); head.accounts(); head.results(); head.activity(); head.accountsFor('Term 1');
assert.equal(JSON.stringify(bursar.forYear('ay-1')), stateBefore, 'Oversight reads cannot rewrite source ledgers');
TestBed.flushEffects(); TestBed.resetTestingModule();
console.log('Head oversight checks passed: live fees/payments/voids/adjustments, academic review and registry updates, shared grades, role attribution, term filters, independent years and non-mutating views.');
