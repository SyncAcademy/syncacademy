const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');

module.exports = async ({ t, db, client, fixture }) => {
  await t.test('finance totals, validation, school isolation and staff handover', async () => {
    await db.rateBucket.deleteMany();
    const school = await db.school.create({ data: { name: 'Finance test', code: 'FIN-TEST', region: 'Test' } });
    const year = await db.academicYear.create({ data: { schoolId: school.id, name: '2026', startsAt: new Date('2026-01-01'), endsAt: new Date('2026-12-31') } });
    const cls = await db.classroom.create({ data: { schoolId: school.id, yearId: year.id, name: 'Form 1A' } });
    const otherClass = await db.classroom.create({ data: { schoolId: school.id, yearId: year.id, name: 'Form 1B' } });
    const student = await db.student.create({ data: { schoolId: school.id, name: "Amina O'Neil", admissionNumber: 'FIN-001' } });
    const enrollment = await db.enrollment.create({ data: { schoolId: school.id, studentId: student.id, classroomId: cls.id } });
    const oldUser = await fixture('finance-old@example.test', 'BURSAR', school.id);
    const old = client(); assert.equal((await old.login(oldUser.email, undefined, 'BURSAR')).status, 201);
    const route = `schools/${school.id}/finance/`;
    const call = (agent, method, path, data, key = randomUUID()) => agent.call(method, route + path, data, { 'Idempotency-Key': key });
    const post = (path, data) => call(old, 'POST', path, data);
    const get = path => call(old, 'GET', path);
    const feeData = { yearId: year.id, classroomId: cls.id, term: 'Term 1', name: 'Tuition', amount: 100000, dueDate: '2026-01-01' };
    assert.equal((await post('fees', { ...feeData, dueDate: '2026-02-31' })).status, 400);
    const bulkData = { ...feeData, classroomId: undefined, classroomIds: [cls.id, otherClass.id], name: 'Multiple-class contribution' };
    const bulkKey = randomUUID();
    const bulk = await call(old, 'POST', 'fees', bulkData, bulkKey);
    assert.equal(bulk.status, 201, JSON.stringify(bulk.body)); assert.equal(bulk.body.fees.length, 2);
    assert.deepEqual((await call(old, 'POST', 'fees', bulkData, bulkKey)).body, bulk.body, 'bulk creation retry is idempotent');
    assert.equal((await post('fees', { ...bulkData, classroomIds: [cls.id, randomUUID()], name: 'Invalid class batch' })).status, 400);
    assert.equal(await db.feeStructure.count({ where: { schoolId: school.id, name: 'Invalid class batch' } }), 0, 'invalid class cannot partially create fees');
    assert.equal((await post('fees', bulkData)).status, 409);
    assert.equal((await post('fees', { ...bulkData, classroomIds: [] })).status, 400);
    assert.equal((await post('fees', { ...bulkData, classroomIds: [cls.id, cls.id] })).status, 400);
    let result = await post('fees', feeData); assert.equal(result.status, 201, JSON.stringify(result.body)); const fee = result.body;
    assert.equal((await call(old, 'PATCH', `fees/${fee.id}`, { name: 'Tuition revised' })).status, 200);
    assert.equal((await post(`fees/${fee.id}/apply`, {})).body.count, 1);
    assert.equal((await post(`fees/${fee.id}/apply`, {})).body.count, 0);
    assert.equal((await call(old, 'PATCH', `fees/${fee.id}`, { amount: 5 })).status, 409);
    const second = (await post('fees', { ...feeData, name: 'Meals', amount: 50000 })).body;
    await post(`fees/${second.id}/apply`, {});
    const paymentData = { yearId: year.id, studentId: student.id, term: 'Term 1', amount: 40000, method: 'Bank transfer', reference: '  FIN-TX  ', date: '2026-01-05' };
    assert.equal((await post('payments', { ...paymentData, date: '2026-02-31' })).status, 400);
    const paymentKey = randomUUID();
    result = await call(old, 'POST', 'payments', paymentData, paymentKey); assert.equal(result.status, 201, JSON.stringify(result.body)); let payment = result.body;
    assert.equal(payment.reference, 'FIN-TX');
    assert.equal((await call(old, 'POST', 'payments', paymentData, paymentKey)).body.id, payment.id);
    assert.equal((await post('payments', { ...paymentData, amount: 999999999 })).status, 400);
    assert.equal((await post('payments', paymentData)).status, 409);
    assert.equal((await post('adjustments', { yearId: year.id, studentId: student.id, term: 'Term 1', amount: 10000, kind: 'Scholarship', reason: 'Approved school scholarship.' })).status, 201);
    const summary = await get(`summary?yearId=${year.id}`);
    assert.equal(summary.status, 200, JSON.stringify(summary.body));
    assert.equal(summary.body.charged, 150000); assert.equal(summary.body.paid, 40000); assert.equal(summary.body.balance, 100000); assert.equal(summary.body.overdue, 100000);
    const reports = (await get(`reports?yearId=${year.id}`)).body;
    assert.equal(reports.find(r => r.classroomId === cls.id).paid, 40000, 'multiple fees must not multiply a receipt');
    assert.equal(reports.find(r => r.classroomId === otherClass.id).balance, 0);
    assert.equal((await get(`accounts?yearId=${year.id}&classroomId=${otherClass.id}`)).body.total, 0);
    assert.equal((await get(`accounts?yearId=${year.id}&search=${encodeURIComponent("O'Neil")}`)).body.total, 1);
    assert.equal((await get(`accounts?yearId=${year.id}&search=${encodeURIComponent("' OR 1=1 --")}`)).body.total, 0);
    assert.equal((await get(`summary?yearId=${year.id}&term=${encodeURIComponent("' OR 1=1 --")}`)).status, 400);
    assert.equal((await post(`payments/${payment.id}/void`, { reason: 'Correcting the original receipt.' })).status, 201);
    const afterVoid = (await get(`summary?yearId=${year.id}`)).body;
    assert.equal(afterVoid.paid, 0); assert.equal(afterVoid.balance, 140000, 'void restores the balance while keeping the scholarship');
    assert.equal((await post(`payments/${payment.id}/void`, { reason: 'Cannot void the same receipt twice.' })).status, 409);
    const replacement = await post('payments', paymentData);
    assert.equal(replacement.status, 201, JSON.stringify(replacement.body));
    assert.notEqual(replacement.body.receipt, payment.receipt, 'replacement payment receives a distinct receipt');
    payment = replacement.body;
    assert.equal((await get(`summary?yearId=${year.id}`)).body.balance, 100000);
    const annual = await post('fees', { ...feeData, term: 'Full year', name: 'Annual contribution', amount: 20000 });
    assert.equal(annual.status, 201, JSON.stringify(annual.body));
    assert.equal((await post(`fees/${annual.body.id}/apply`, {})).body.count, 1);
    assert.equal((await post(`fees/${annual.body.id}/apply`, {})).body.count, 0);
    assert.equal((await post('payments', { ...paymentData, term: 'Full year', amount: 5000, reference: 'ANNUAL-TX' })).status, 201);
    assert.equal((await post('adjustments', { yearId: year.id, studentId: student.id, term: 'Full year', amount: 1000, kind: 'Discount', reason: 'Approved annual contribution discount.' })).status, 201);
    const annualSummary = (await get(`summary?yearId=${year.id}&term=Full%20year`)).body;
    assert.equal(annualSummary.balance, 14000); assert.equal(annualSummary.overdue, 14000);
    assert.equal((await get(`summary?yearId=${year.id}&term=Term%201`)).body.balance, 100000, 'annual payments do not reduce term-specific balances');
    assert.equal((await get(`summary?yearId=${year.id}`)).body.balance, 114000, 'all-period totals include annual charges exactly once');
    const secondInstallment = await post('payments', { ...paymentData, amount: 10000, reference: 'SECOND-INSTALLMENT' });
    assert.equal(secondInstallment.status, 201);
    assert.equal((await get(`summary?yearId=${year.id}&term=Term%201`)).body.balance, 90000, 'each installment reduces the remaining period balance');
    const studentAccount = (await get(`accounts/${student.id}?yearId=${year.id}`)).body;
    assert.equal(studentAccount.charges.length, 3, 'one student account includes every applied fee');
    const tuitionCharge = studentAccount.charges.find(c => c.feeId === fee.id);
    const mealsCharge = studentAccount.charges.find(c => c.feeId === second.id);
    const assignedPayment = { ...paymentData, chargeId: mealsCharge.id, amount: 20000, reference: 'MEALS-INSTALLMENT' };
    const assigned = await post('payments', assignedPayment);
    assert.equal(assigned.status, 201, JSON.stringify(assigned.body));
    assert.equal(assigned.body.chargeId, mealsCharge.id);
    assert.equal((await post('payments', { ...assignedPayment, reference: 'MEALS-OVERPAY', amount: 30001 })).status, 400, 'cannot exceed fee balance even with other unpaid fees');
    assert.equal((await post('payments', { ...assignedPayment, reference: 'INVALID-FEE', chargeId: randomUUID() })).status, 400);
    assert.equal((await post('payments', { ...assignedPayment, reference: 'WRONG-PERIOD', term: 'Full year' })).status, 400);
    const anotherStudent = await db.student.create({ data: { schoolId: school.id, name: 'Other student', admissionNumber: 'FIN-002' } });
    assert.equal((await post('payments', { ...assignedPayment, reference: 'WRONG-STUDENT', studentId: anotherStudent.id })).status, 400);
    assert.equal((await post(`payments/${assigned.body.id}/void`, { reason: 'Correcting fee allocation.' })).status, 201);
    assert.equal((await post('payments', { ...assignedPayment, amount: 50000, reference: 'MEALS-FULL' })).status, 201, 'void restores fee availability');
    const registrarUser = await fixture('finance-registrar@example.test', 'REGISTRAR', school.id);
    const registrarAgent = client(); await registrarAgent.login(registrarUser.email, undefined, 'REGISTRAR');
    assert.equal((await call(registrarAgent, 'GET', `fees?yearId=${year.id}`)).status, 200);
    const registrarPayment = await call(registrarAgent, 'POST', 'payments', { ...paymentData, chargeId: tuitionCharge.id, amount: 1000, reference: 'REGISTRAR-PAYMENT' });
    assert.equal(registrarPayment.status, 201, JSON.stringify(registrarPayment.body));
    assert.equal((await call(registrarAgent, 'POST', 'fees', { ...feeData, name: 'Unauthorized fee' })).status, 403);
    assert.equal((await call(registrarAgent, 'POST', `payments/${registrarPayment.body.id}/void`, { reason: 'Not permitted for registrar.' })).status, 403);
    const correctionBody = { ...paymentData, chargeId: tuitionCharge.id, amount: 2000, reference:'REGISTRAR-CORRECTED', reason:'Amount was entered incorrectly.' };
    const correctionKey = randomUUID();
    const correctionPath = `payments/${registrarPayment.body.id}/correct`;
    assert.equal((await call(registrarAgent, 'POST', correctionPath, {...correctionBody, amount:99999999})).status, 400);
    assert.equal((await db.payment.findUnique({where:{id:registrarPayment.body.id}})).voidAt, null, 'failed correction does not reverse original');
    assert.equal((await call(registrarAgent, 'POST', correctionPath, {...correctionBody, reason:'short'})).status, 400);
    const corrected = await call(registrarAgent, 'POST', correctionPath, correctionBody, correctionKey);
    assert.equal(corrected.status, 201, JSON.stringify(corrected.body));
    assert.equal(corrected.body.replacesId, registrarPayment.body.id);
    assert.notEqual(corrected.body.receipt, registrarPayment.body.receipt);
    assert.equal((await call(registrarAgent, 'POST', correctionPath, correctionBody, correctionKey)).body.id, corrected.body.id, 'correction retry creates one receipt');
    assert.equal((await call(registrarAgent, 'POST', correctionPath, correctionBody)).status, 409, 'cannot correct original twice');
    const originalReceipt = await db.payment.findUnique({where:{id:registrarPayment.body.id}});
    assert.ok(originalReceipt.voidAt); assert.equal(originalReceipt.amount, 1000);
    assert.ok(originalReceipt.voidReason.includes(corrected.body.receipt));
    assert.equal((await get(`summary?yearId=${year.id}&term=Term%201`)).body.paid, 102000, 'only replacement amount counts');
    const overdueFee = (await post('fees', { ...feeData, term:'Term 2', name:'Overdue tuition', amount:10000 })).body;
    const futureFee = (await post('fees', { ...feeData, term:'Term 2', name:'Future meals', amount:10000, dueDate:'2026-12-31' })).body;
    await post(`fees/${overdueFee.id}/apply`, {}); await post(`fees/${futureFee.id}/apply`, {});
    const futureCharge = await db.studentCharge.findFirst({where:{feeId:futureFee.id}});
    assert.equal((await post('payments', {...paymentData, term:'Term 2', chargeId:futureCharge.id, amount:1000, reference:'FUTURE-FEE'})).status, 201);
    assert.equal((await get(`summary?yearId=${year.id}&term=Term%202`)).body.overdue, 10000, 'paying a future fee must not clear overdue tuition');
    await db.enrollment.update({ where: { id: enrollment.id }, data: { status: 'graduated' } });
    await db.academicYear.update({ where: { id: year.id }, data: { closed: true } });
    assert.equal((await call(registrarAgent, 'POST', `payments/${corrected.body.id}/correct`, correctionBody)).status, 201, 'historical year permits receipt corrections');
    await db.membership.updateMany({ where: { userId: oldUser.id }, data: { active: false } });
    assert.equal((await get(`ledger?yearId=${year.id}`)).status, 403);
    for (const role of ['BURSAR', 'HEADMASTER', 'REGISTRAR', 'ACADEMIC']) {
      const user = await fixture(`new-${role.toLowerCase()}@example.test`, role, school.id);
      const agent = client(); await agent.login(user.email, undefined, role);
      const workspace = await agent.call('GET', `schools/${school.id}/workspace`);
      assert.equal(workspace.status, 200, JSON.stringify(workspace.body));
      if(['BURSAR','HEADMASTER'].includes(role)) {
        const charges=await db.studentCharge.findMany({where:{schoolId:school.id},select:{studentId:true,amount:true}});
        const payments=await db.payment.findMany({where:{schoolId:school.id,voidAt:null},select:{studentId:true,amount:true}});
        const adjustments=await db.adjustment.findMany({where:{schoolId:school.id},select:{studentId:true,amount:true}});
        const owing=[...new Set(charges.map(c=>c.studentId))].filter(id=>charges.filter(c=>c.studentId===id).reduce((n,c)=>n+c.amount,0)+adjustments.filter(a=>a.studentId===id).reduce((n,a)=>n+a.amount,0)-payments.filter(p=>p.studentId===id).reduce((n,p)=>n+p.amount,0)>0).length;
        assert.equal(workspace.body.financeSummary.studentsOwing,owing,'grouped dashboard totals preserve charges, adjustments and non-void payments');
      }
      for (const row of workspace.body.students) for (const enrollment of row.enrollments) {
        const expected = await db.enrollmentSubject.findMany({where:{schoolId:school.id,enrollmentId:enrollment.id},select:{subjectId:true}});
        assert.deepEqual(enrollment.subjects.map(s=>s.subjectId).sort(),expected.map(s=>s.subjectId).sort(),'batched subjects preserve the authorized enrollment response');
      }
      assert.ok(workspace.body.years.some(y => y.id === year.id));
      assert.ok(workspace.body.students.some(s => s.id === student.id && s.enrollments.some(e => e.status === 'graduated')));
      const finance = await call(agent, 'GET', `ledger?yearId=${year.id}`);
      assert.equal(finance.status, ['BURSAR', 'HEADMASTER', 'REGISTRAR'].includes(role) ? 200 : 403);
      if (role === 'BURSAR') {
        assert.ok(finance.body.payments.some(p => p.id === payment.id));
        assert.equal((await call(agent, 'POST', `payments/${payment.id}/void`, { reason: 'Correcting a historical receipt.' })).status, 201);
        assert.equal((await call(agent, 'POST', 'payments', paymentData)).status, 201);
      }
      if (role === 'ACADEMIC') {
        const teacher = await fixture('new-history-teacher@example.test', 'TEACHER', school.id);
        const membership = await db.membership.findFirstOrThrow({ where: { userId: teacher.id } });
        const grant = await agent.call('POST', `schools/${school.id}/academics/commands`, { yearId: year.id, action: 'class-teacher', payload: { teacherId: membership.id, classId: cls.id } }, { 'Idempotency-Key': randomUUID() });
        assert.equal(grant.status, 201, JSON.stringify(grant.body));
        const teacherClient = client(); await teacherClient.login(teacher.email, undefined, 'TEACHER');
        const history = (await teacherClient.call('GET', `schools/${school.id}/workspace`)).body;
        assert.equal(history.students[0].id, student.id); assert.equal(history.students[0].enrollments[0].status, 'graduated');
        assert.equal((await call(teacherClient, 'GET', `ledger?yearId=${year.id}`)).status, 403);
      }
    }
    const other = await db.school.create({ data: { name: 'Other finance school', code: 'FIN-OTHER', region: 'Test' } });
    const outsiderUser = await fixture('finance-outsider@example.test', 'BURSAR', other.id);
    const outsider = client(); await outsider.login(outsiderUser.email, undefined, 'BURSAR');
    assert.equal((await call(outsider, 'GET', `ledger?yearId=${year.id}`)).status, 403);
    assert.equal((await outsider.call('GET',`schools/${other.id}/workspace`)).body.financeSummary.studentsOwing,0,'dashboard balances stay within their school');
  });
};
